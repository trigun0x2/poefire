"""Regenerate src/poefire/pob_tree.py from Path of Building's passive tree data.

Run when a new league adds a tree version (see PoB's src/GameVersions.lua):

    uv run python scripts/update_pob_tree.py 3_29
    uv run python scripts/update_pob_tree.py --latest   # PoB's newest tree (weekly workflow)

It reads PathOfBuildingCommunity/PathOfBuilding's TreeData/<version>/tree.lua and keeps only
what poefire's PoB export needs: the classes with their ascendancies (for classId /
ascendClassId) and the order of the jewel sockets (the website reports tree jewels by index).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import httpx

URL = "https://raw.githubusercontent.com/PathOfBuildingCommunity/PathOfBuilding/master/src/TreeData/{}/tree.lua"
VERSIONS_URL = "https://raw.githubusercontent.com/PathOfBuildingCommunity/PathOfBuilding/master/src/GameVersions.lua"
OUT = Path(__file__).resolve().parents[1] / "src" / "poefire" / "pob_tree.py"


def latest_version() -> str:
    """PoB's newest regular tree version: "3_29" (not the _ruthless / _alternate ones)."""
    r = httpx.get(VERSIONS_URL, timeout=60, follow_redirects=True)
    r.raise_for_status()
    listed = re.search(r"treeVersionList\s*=\s*\{(.*?)\}", r.text, re.S)
    if listed is None:
        raise SystemExit("treeVersionList not found in GameVersions.lua")
    regular = re.findall(r'"(\d+_\d+)"', listed.group(1))
    return max(regular, key=lambda v: tuple(int(x) for x in v.split("_")))


def block(lines: list[str], start: str) -> str:
    i = next(i for i, line in enumerate(lines) if re.match(start, line))
    depth, buf = 0, []
    for line in lines[i:]:
        buf.append(line)
        depth += line.count("{") - line.count("}")
        if depth == 0 and len(buf) > 1:
            break
    return "\n".join(buf)


def main(version: str) -> None:
    lua = httpx.get(URL.format(version), timeout=120, follow_redirects=True)
    lua.raise_for_status()
    lines = lua.text.split("\n")
    classes = []
    for m in re.finditer(r'\n        \{\n            \["name"\]= "([^"]+)"(.*?)\n        \}',
                         block(lines, r'^    \["classes"\]= \{'), re.S):  # fmt: skip
        ascendancies = re.findall(r'\["id"\]= "[^"]+",\s*\n\s*\["name"\]= "([^"]+)"', m.group(2))
        classes.append((m.group(1), ascendancies))
    slots = [int(x) for x in re.findall(r"\d+", block(lines, r'^    \["jewelSlots"\]= \{'))]
    body = [
        '"""Path of Building passive tree data used by poefire.pob.',
        "",
        f"Generated by scripts/update_pob_tree.py from PoB's TreeData/{version}/tree.lua;",
        'don\'t edit by hand."""',
        "",
        f'TREE_VERSION = "{version}"',
        "",
        "# class -> its ascendancies; classId = position (from 0), ascendClassId = position + 1",
        "CLASSES: list[tuple[str, list[str]]] = [",
        *[f"    ({name!r}, {asc!r})," for name, asc in classes],
        "]",
        "",
        "# tree jewel socket node ids, in the order the website's jewel `x` indexes them",
        f"JEWEL_SLOTS: list[int] = {slots!r}",
        "",
    ]
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {OUT}: {len(classes)} classes, {len(slots)} jewel sockets")


if __name__ == "__main__":
    arg = sys.argv[1] if len(sys.argv) > 1 else "--latest"
    main(latest_version() if arg == "--latest" else arg)
